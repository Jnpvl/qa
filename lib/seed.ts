const PROJECT = "prj_tienda"

function caso(
  number: number,
  suiteId: string,
  title: string,
  preconditions: string,
  pairs: [string, string][],
  extra: {
    priority: Priority
    severity: Severity
    kind: CaseKind
    executionType: ExecutionType
    tags: string[]
    status: CaseStatus
    sprintIds: string[]
    updatedAt: string
  },
): TestCase {
  return {
    id: `cse_${String(number).padStart(2, "0")}`,
    projectId: PROJECT,
    suiteId,
    number,
    title,
    preconditions,
    steps: pairs.map(([action, expected], index) => ({
      id: `st_${String(number).padStart(2, "0")}_${index + 1}`,
      action,
      expected,
    })),
    ...extra,
  }
}

function result(number: number, status: ResultStatus, comment = "") {
  return {
    caseId: `cse_${String(number).padStart(2, "0")}`,
    status,
    comment,
  }
}

